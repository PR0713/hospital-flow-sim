"""Freeze the instance seeds of the benchmark tiers. Run once per new tier:

    .venv/bin/python benchmarks/tiers/make_seeds.py T5

Writes ``benchmarks/tiers/<tier>/seeds.yaml`` with 100 eval and 200 test
seeds. Seed ``i`` of a split is ``instance_seed(TIER_BASE_SEED, split, i, r)``
with the smallest ``r`` whose instance has a patient and fits the
environment's default padding. Refuses to overwrite an existing file.
"""

from __future__ import annotations

import sys

from hospital_sim.env import EnvConfig, HospitalEnv, instance_seed
from hospital_sim.eval.tiers import N_EVAL, N_TEST, TIER_BASE_SEED, TIER_ROOT, config_digest
from hospital_sim.generators import generate_instance, load_scenario


def freeze(name: str) -> None:
    folder = TIER_ROOT / name
    out = folder / "seeds.yaml"
    if out.exists():
        raise SystemExit(f"{out} exists; tiers are frozen")
    scenario = load_scenario(folder / "config.yaml")
    env = HospitalEnv(EnvConfig(scenario))
    lists: dict[str, list[int]] = {}
    for split, count in (("eval", N_EVAL), ("test", N_TEST)):
        seeds = []
        for episode in range(count):
            for resample in range(256):
                seed = instance_seed(TIER_BASE_SEED, split, episode, resample)
                instance = generate_instance(scenario, seed)
                if instance.patients and env._fits(instance):
                    seeds.append(seed)
                    break
            else:
                raise RuntimeError(f"{name}: no usable instance for {split} episode {episode}")
        lists[split] = seeds
    lines = [
        f"# Frozen instance seeds of benchmark tier {name} (hospital_sim v0.1).",
        "# Generated by benchmarks/tiers/make_seeds.py; never edit by hand.",
        "# eval: tune and select on these. test: report on these.",
        f"tier: {name}",
        f"base_seed: {TIER_BASE_SEED}",
        f"config_sha256: {config_digest(folder / 'config.yaml')}",
    ]
    for split in ("eval", "test"):
        lines.append(f"{split}:")
        lines.extend(f"  - {seed}" for seed in lists[split])
    out.write_text("\n".join(lines) + "\n")
    print(f"{out}: {len(lists['eval'])} eval, {len(lists['test'])} test seeds")


if __name__ == "__main__":
    for tier in sys.argv[1:]:
        freeze(tier)
