"""Regenerates docs/SENSITIVITY.md.

Run with: .venv/bin/python benchmarks/run_m5_studies.py
"""

from __future__ import annotations

from pathlib import Path

from hospital_sim.baselines import all_policies
from hospital_sim.env import EnvConfig, HospitalEnv
from hospital_sim.eval.sensitivity import (
    LEAVE_PENALTY,
    PARTIAL_SOURCES,
    SensitivityResult,
    format_report,
    run_sensitivity,
)
from hospital_sim.generators import load_scenario

ROOT = Path(__file__).parent.parent
EPISODES = 200


def cost_table(result: SensitivityResult) -> list[str]:
    return [
        "| Variant | " + " | ".join(result.cost_all_on) + " |",
        "|---|" + "---|" * len(result.cost_all_on),
        "| everything on | " + " | ".join(f"{v:.1f}" for v in result.cost_all_on.values()) + " |",
        *[
            f"| {e.source} off | " + " | ".join(f"{v:.1f}" for v in e.cost_when_off.values()) + " |"
            for e in result.effects
        ],
        "",
    ]


if __name__ == "__main__":
    full = load_scenario(ROOT / "configs" / "example_hospital_full.yaml")
    patience = load_scenario(ROOT / "configs" / "example_hospital_patience.yaml")
    policies = all_policies()
    penalty = HospitalEnv(EnvConfig(full)).leave_penalty  # the environment's default
    patience_penalty = HospitalEnv(EnvConfig(patience)).leave_penalty

    main = run_sensitivity(full, policies, EPISODES, penalty)
    partial = run_sensitivity(full, policies, EPISODES, penalty, sources=list(PARTIAL_SOURCES))
    leaving = run_sensitivity(
        patience, policies, EPISODES, patience_penalty, sources=["leaving", LEAVE_PENALTY]
    )

    text = "\n".join(
        [
            "# Noise-source sensitivity",
            "",
            "Generated by `benchmarks/run_m5_studies.py`.",
            "",
            f"Scenario `{full.name}` (every source on), {EPISODES} episodes from the `eval`",
            f"split, all {len(policies)} baselines with the `flexible` allocation rule. Each",
            "source is switched off on its own and the same seeds are run again. Times in minutes.",
            "",
            "`cost` is the default objective per unit of patient weight: weighted mean flow",
            f"time plus the leave penalty ({penalty:.0f} per unit weight of a patient who leaves).",
            "",
            "How to read this:",
            "",
            "- A large effect with a tau near 1 means the source changes how hard the problem",
            "  is, but not which policy is better.",
            "- A tau well below 1 means the source changes the ranking: it must be modelled",
            "  to compare policies correctly.",
            f"- With {len(policies)} policies tau moves in steps of about 0.07, so small",
            "  differences from 1 are not meaningful.",
            "- Effects are measured on baseline dispatching rules. A source can matter more",
            "  to an agent that exploits it than it does here.",
            "",
            "These are properties of an illustrative config, not findings about a hospital.",
            "",
            "## 1. Every source, one at a time",
            "",
            format_report(main),
            "**Two rows combine two effects each.**",
            "",
            "- `arrival_variability` off makes arrivals evenly spaced and punctual, and as a",
            "  side effect turns walk-ins into a booking list that is visible in advance. So",
            "  it removes randomness in timing *and* adds foresight. The baselines ignore the",
            "  booking list, so here the row measures timing only; for an agent it would not.",
            "- `reveal` off makes gated steps known on arrival *and* removes the repeat scans,",
            "  so it mixes an information effect with a workload effect.",
            "",
            "Section 2 separates them.",
            "",
            "Mean cost of every policy:",
            "",
            *cost_table(main),
            "## 2. Narrower switches",
            "",
            "- `arrival_bursts_and_profile`: arrivals stay random and unannounced, but at a",
            "  constant rate without bursts. Isolates clumping and time-of-day peaks from",
            "  the rest of arrival randomness, with no change in what is visible.",
            "- `reveal_information_only`: gated steps are known on arrival; repeats and their",
            "  workload stay. Isolates the information effect. (With gating removed the link",
            "  between hidden complexity and these steps is also off, so which patients get",
            "  them changes, though not how many on average.)",
            "- `repeat_workload_only`: repeats are removed; gated steps stay hidden. Isolates",
            "  the workload effect.",
            "",
            "There is no switch that removes arrival-time randomness while keeping arrivals",
            "unannounced; that would need a new arrival kind.",
            "",
            format_report(partial),
            "## 3. Leaving and the leave penalty, where patience binds",
            "",
            f"In `{full.name}` almost nobody leaves, so its `leaving` and `leave_penalty` rows",
            f"above say little. `{patience.name}` has twice the walk-ins, four nurses instead of",
            "six and a mean patience of 20 minutes; under FIFO about two walk-ins per episode",
            f"give up. Same method, {EPISODES} episodes, leave penalty {patience_penalty:.0f}.",
            "",
            format_report(leaving),
            "With leaving switched off the same patients stay and are eventually treated, so",
            "flow time and makespan rise while the penalty disappears: `leaving` off is not",
            'simply "better". The `leave_penalty` row reuses the same episodes with the penalty',
            "set to zero, so only the cost and the ranking can change.",
            "",
            "Mean cost of every policy:",
            "",
            *cost_table(leaving),
        ]
    )
    (ROOT / "docs" / "SENSITIVITY.md").write_text(text)
    print("wrote docs/SENSITIVITY.md")
