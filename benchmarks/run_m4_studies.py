"""Regenerates docs/BASELINE_RESULTS.md and docs/ALLOCATION_GAP.md.

Run with: .venv/bin/python benchmarks/run_m4_studies.py
"""

from __future__ import annotations

import dataclasses
from pathlib import Path

import numpy as np

from hospital_sim.baselines import (
    DISPATCHERS,
    Policy,
    SearchTooLarge,
    all_policies,
    best_allocation,
)
from hospital_sim.domain import Scenario
from hospital_sim.eval import evaluate, sample_instances
from hospital_sim.generators import load_scenario
from hospital_sim.sim import Simulator, compute_metrics
from hospital_sim.sim.allocation import RULES

ROOT = Path(__file__).parent.parent
EPISODES = 200
SEARCH_INSTANCES = 60


def configs() -> dict[str, Scenario]:
    return {
        "example_hospital": load_scenario(ROOT / "configs" / "example_hospital.yaml"),
        "four_surgeons": load_scenario(ROOT / "configs" / "four_surgeons.yaml"),
        "four_surgeons_speed": load_scenario(ROOT / "configs" / "four_surgeons_speed.yaml"),
        "example_hospital_dynamic": load_scenario(
            ROOT / "configs" / "example_hospital_dynamic.yaml"
        ),
        "example_hospital_stress": load_scenario(ROOT / "configs" / "example_hospital_stress.yaml"),
        "example_hospital_full": load_scenario(ROOT / "configs" / "example_hospital_full.yaml"),
    }


def baseline_report(scenarios: dict[str, Scenario]) -> str:
    out = [
        "# Baseline results",
        "",
        f"Generated by `benchmarks/run_m4_studies.py`. {EPISODES} episodes per config from the",
        "`eval` seed split, every policy on the same instances, allocation rule `flexible`.",
        "Cells are mean ± half-width of the 95% confidence interval; times in minutes.",
        "Policies are ordered by weighted mean flow time (the default objective).",
        "`left` is the number of patients per episode who gave up waiting before being seen,",
        "and `no_show` the number of booked patients who never came; both are zero in configs",
        "without those features. Read flow time together with `left`: a policy can shorten",
        "flow time by letting patients leave.",
        "",
        "These are results on illustrative configs, not on a model of any real hospital.",
        "",
    ]
    for name in (
        "example_hospital",
        "example_hospital_dynamic",
        "example_hospital_stress",
        "example_hospital_full",
    ):
        result = evaluate(scenarios[name], all_policies(), EPISODES)
        out += [f"## {name}", ""]
        out += [
            result.table(
                (
                    "weighted_mean_flow_time",
                    "mean_flow_time",
                    "makespan",
                    "mean_op_wait",
                    "left",
                    "no_show",
                )
            ),
            "",
        ]
        best = result.ranking("weighted_mean_flow_time")[0]
        out += [
            f"Paired difference in weighted mean flow time against `{best}` (same instances):",
            "",
        ]
        out += ["| Policy | difference | 95% CI half-width |", "|---|---|---|"]
        for policy in result.ranking("weighted_mean_flow_time")[1:]:
            diff, half = result.paired_difference("weighted_mean_flow_time", policy, best)
            out.append(f"| {policy} | +{diff:.1f} | {half:.1f} |")
        out.append("")
        classes = result.by_class(best, "mean_flow_time")
        if len(classes) > 1:
            out += ["Mean flow time by patient class:", ""]
            out += ["| Policy | " + " | ".join(classes) + " |", "|---|" + "---|" * len(classes)]
            for policy in result.ranking("weighted_mean_flow_time"):
                per = result.by_class(policy, "mean_flow_time")
                out.append(
                    f"| {policy} | "
                    + " | ".join(f"{per[c][0]:.1f} ± {per[c][2]:.1f}" for c in classes)
                    + " |"
                )
            out.append("")
        out += [f"Utilization under `{best}` (busy time over on-duty time):", ""]
        util = result.utilization(best)
        out += ["| " + " | ".join(util) + " |", "|" + "---|" * len(util)]
        out += ["| " + " | ".join(f"{v[0]:.2f}" for v in util.values()) + " |", ""]

    name = "example_hospital_full"
    out += [
        f"## Allocation rules on {name}",
        "",
        "The same dispatcher under each allocation rule, same instances. The full study on",
        "the other configs is in `docs/ALLOCATION_GAP.md`.",
        "",
    ]
    for dispatcher in ("fifo", "urgent_first", "weight_aware"):
        result = evaluate(scenarios[name], [Policy(dispatcher, rule) for rule in RULES], EPISODES)
        columns = ("weighted_mean_flow_time", "mean_flow_time", "makespan", "left")
        out += [f"Dispatcher `{dispatcher}`:", "", result.table(columns), ""]
        for rule in RULES:
            if rule != "flexible":
                diff, half = result.paired_difference(
                    "weighted_mean_flow_time", f"{dispatcher}+{rule}", f"{dispatcher}+flexible"
                )
                out.append(f"- `{rule}` minus `flexible`: {diff:+.1f} ± {half:.1f}")
        out.append("")
    return "\n".join(out)


def flow(sim: Simulator) -> float:
    return compute_metrics(sim).mean_flow_time


def allocation_report(scenarios: dict[str, Scenario]) -> str:
    rules = list(RULES)
    out = [
        "# Allocation gap",
        "",
        "Generated by `benchmarks/run_m4_studies.py`. How much does the choice of team matter",
        "when the dispatching rule is held fixed? Times in minutes.",
        "",
        "## 1. Same dispatcher, each allocation rule",
        "",
        f"{EPISODES} episodes per config (`eval` split, common instances). Each cell is the mean",
        "flow time under that rule; the second line is its paired difference from `flexible`",
        "with the 95% CI half-width. A difference whose interval excludes zero is real.",
        "Patients can leave only in `example_hospital_full`; its leaver counts per rule are in",
        "`docs/BASELINE_RESULTS.md`.",
        "",
    ]
    for dispatcher in ("fifo", "spt", "weight_aware"):
        out += [
            f"### Dispatcher: {dispatcher}",
            "",
            "| Config | " + " | ".join(rules) + " |",
            "|---|" + "---|" * len(rules),
        ]
        for name, scenario in scenarios.items():
            result = evaluate(scenario, [Policy(dispatcher, rule) for rule in rules], EPISODES)
            cells = []
            for rule in rules:
                mean = result.summary("mean_flow_time")[f"{dispatcher}+{rule}"][0]
                if rule == "flexible":
                    cells.append(f"{mean:.1f}")
                else:
                    diff, half = result.paired_difference(
                        "mean_flow_time", f"{dispatcher}+{rule}", f"{dispatcher}+flexible"
                    )
                    cells.append(f"{mean:.1f} ({diff:+.1f} ± {half:.1f})")
            out.append(f"| {name} | " + " | ".join(cells) + " |")
        out.append("")

    out += [
        "## 2. Search-based reference on small instances",
        "",
        f"{SEARCH_INSTANCES} instances of 4 patients per config, dispatcher `fifo`. The reference",
        "tries every distinct team at every start and keeps the best mean flow time. It is a",
        "hindsight bound: it sees how each choice turns out, so no online rule can beat it.",
        "Cells are the mean excess over the reference, in percent, and the share of instances",
        "on which the rule matches the reference exactly.",
        "",
        "**Scope of this reference.** It covers 4-patient instances under one dispatcher only,",
        "because the search grows exponentially with the number of team choices. It says",
        "nothing direct about full-size episodes, where longer queues give allocation more",
        "room to matter; section 1 is the evidence there, and it compares rules with each",
        "other, not with an optimum.",
        "",
        "| Config | " + " | ".join(rules) + " | mean schedules searched |",
        "|---|" + "---|" * (len(rules) + 1),
    ]
    for name in ("example_hospital", "four_surgeons", "four_surgeons_speed"):
        small = dataclasses.replace(
            scenarios[name],
            arrivals=(dataclasses.replace(scenarios[name].arrivals[0], n_patients=4),),
        )
        gaps: dict[str, list[float]] = {rule: [] for rule in rules}
        leaves = []
        for instance in sample_instances(small, SEARCH_INSTANCES):
            try:
                best, n = best_allocation(instance, "fifo", flow)
            except SearchTooLarge:
                continue
            leaves.append(n)
            for rule in rules:
                gaps[rule].append(flow(Policy("fifo", rule).run(instance)) / best - 1.0)
        cells = [
            f"{100 * np.mean(g):.1f}% ({100 * np.mean(np.array(g) < 1e-9):.0f}% optimal)"
            for g in gaps.values()
        ]
        out.append(
            f"| {name} ({len(leaves)} solved) | "
            + " | ".join(cells)
            + f" | {np.mean(leaves):.0f} |"
        )
    out.append("")
    return "\n".join(out)


if __name__ == "__main__":
    assert set(DISPATCHERS) >= {"fifo", "spt", "weight_aware"}
    scenarios = configs()
    (ROOT / "docs" / "BASELINE_RESULTS.md").write_text(baseline_report(scenarios))
    (ROOT / "docs" / "ALLOCATION_GAP.md").write_text(allocation_report(scenarios))
    print("wrote docs/BASELINE_RESULTS.md and docs/ALLOCATION_GAP.md")
